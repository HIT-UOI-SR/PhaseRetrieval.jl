@testset "Validation and edge cases" begin
    for solver in (gerchbergsaxton, yanggu)
        for bad in ([-1.,1.], [NaN,1.], [Inf,1.], ComplexF64[1,2], Float64[])
            @test_throws ArgumentError solver(bad, ones(2))
            @test_throws ArgumentError solver(ones(2), bad)
        end
        @test_throws DimensionMismatch solver(ones(2), ones(3))
        @test_throws DimensionMismatch solver(ones(2), ones(2); init=ones(3))
        @test_throws ArgumentError solver(ones(2), ones(2); init=[NaN,1.])
        @test_throws ArgumentError solver(ones(2), ones(2); maxiter=-1)
        @test_throws ArgumentError solver(ones(2), ones(2); maxiter=1.5)
        @test_throws ArgumentError solver(ones(2), ones(2); tol=NaN)
        @test_throws ArgumentError solver(ones(2), ones(2); tol=-1)
        x, y = solver(zeros(3), zeros(3); init=zeros(3), maxiter=2, tol=0)
        @test iszero(x) && iszero(y)
        x, y = solver(Float32[1,2], Float32[3,1]; init=zeros(Float32,2), maxiter=0)
        @test abs.(x) == Float32[1,2]
        @test eltype(x) == ComplexF32
        @test all(isfinite, y)
    end
    @test_throws ArgumentError yanggu(ones(2), ones(2); projector=(fft,ifft))
    @test_throws ArgumentError yanggu(ones(2), ones(2); inneriter=0)
    @test_throws ArgumentError yanggu(ones(2), ones(2); normaldiag=-1)
    @test_throws DimensionMismatch yanggu(ones(2), ones(2); normaldiag=ones(3))
    @test_throws DimensionMismatch yanggu(ones(2), ones(2), ones(3,2))
    @test_throws ArgumentError yanggu(ones(2), ones(2), fill(NaN,2,2))
    @test_throws ArgumentError gerchbergsaxton(ones(2), ones(2); projector=(fft,))
    @test_throws ArgumentError gerchbergsaxton(ones(2), ones(2); projector=(x -> fill(NaN,2),ifft))
    for solver in (hio, raar)
        @test_throws ArgumentError solver(ones(2), ones(2))
        @test_throws DimensionMismatch solver(ones(2), trues(3))
        @test_throws ArgumentError solver([-1.,1.], trues(2))
        @test_throws ArgumentError solver(ones(2), trues(2); beta=1.1)
        @test_throws ArgumentError solver(ones(2), trues(2); beta=-0.1)
        @test_throws ArgumentError solver(ones(2), trues(2); beta=NaN)
        @test_throws ArgumentError solver(ones(2), trues(2); nonnegative=1)
        x, y = solver(zeros(3), falses(3); init=zeros(3), maxiter=3, tol=0)
        @test iszero(x) && iszero(y)
    end
    @test_throws ArgumentError sbmir([ones(3)]; propagators=[])
    @test_throws ArgumentError sbmir([ones(3), [-1.,2.,3.]]; propagators=[(fft,ifft)])
    @test_throws DimensionMismatch sbmir([ones(3), ones(3)]; propagators=[])
    @test_throws DimensionMismatch sbmir([ones(3), ones(4)]; propagators=[(fft,ifft)])
    p = (wavelength=0.1, pixelsize=1.)
    for positions in ([0.,0.], [0.,Inf], [0.,NaN])
        @test_throws ArgumentError sbmir([ones(3),ones(3)], positions; p...)
    end
    @test_throws ArgumentError sbmir([ones(3),ones(3),ones(3)], [0.,2.,1.]; p...)
    @test_throws DimensionMismatch sbmir([ones(3),ones(3)], [0.]; p...)
    @test_throws DimensionMismatch sbmir([ones(3),ones(4)], [0.,1.]; p...)
    fields = sbmir([zeros(3),zeros(3)], [0.,1.]; p..., init=zeros(3), maxiter=3, tol=0)
    @test all(iszero, fields)
    @test_throws ArgumentError fresnelpropagate(ones(3), Inf; p...)
    @test_throws ArgumentError fresnelpropagate(ones(3), 1.; wavelength=0., pixelsize=1.)
    @test_throws ArgumentError fresnelpropagate(ones(3), 1.; wavelength=1., pixelsize=-1.)
    @test_throws DimensionMismatch fresnelpropagate(ones(3,3), 1.; wavelength=1., pixelsize=(1.,))
end
