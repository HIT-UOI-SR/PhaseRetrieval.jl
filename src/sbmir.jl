function _intensities(intensities)
    (intensities isa AbstractVector || intensities isa Tuple) ||
        throw(ArgumentError("intensities must be a vector or tuple of arrays"))
    length(intensities) >= 2 || throw(ArgumentError("at least two intensity planes are required"))
    for intensity in intensities
        _measurement(intensity, "intensity")
    end
    nothing
end

# Propagate one common estimate without applying any measurement constraints.
function _plane_predictions(x, amplitudes, propagators)
    # Custom propagators may change shape, dimensionality, or precision.
    fields = AbstractArray[x]
    for j in 1:length(propagators)
        push!(fields, _propagate(propagators[j][1], fields[end], amplitudes[j+1]))
    end
    fields
end

"""
    sbmir(intensities; propagators, maxiter=100, tol=eps(), errorfunc=msd, init=nothing)
    sbmir(intensities, positions; wavelength, pixelsize, kwargs...)

Single-beam multiple-intensity reconstruction (SBMIR). `intensities` is a vector
or tuple of at least two real nonnegative arrays containing **intensities**;
the algorithm uses their square roots as amplitude constraints. `init` is a
field estimate at the first plane; only its phase is used.

Supply one non-mutating `(forward, backward)` propagation pair per adjacent
pair of planes. An iteration visits `1 → 2 → … → N → … → 2 → 1`, imposing
each visited plane's amplitude. Alternatively, supply strictly monotone plane
`positions`, a `wavelength`, and `pixelsize` for two-dimensional matrix
measurements. This convenience interface calls `OpticalPropagation.fresnel2`
for each adjacent distance, including its carrier phase. Lengths are in metres;
`pixelsize` is a scalar or a pair in array-dimension order. These measurements
must share a grid. For `MonoLightField2D` measurements, pass OpticalPropagation's
unitful propagation functors through `propagators`.

Return a vector of mutually consistent predicted complex fields, generated by
propagating the final first-plane estimate. Only its amplitude is enforced on
return. Stop when the amplitude error at **every** predicted plane is at most
`tol`. `tol=0` disables early stopping; `maxiter=0` returns predictions from the
amplitude-constrained initialization. No input array is modified.

Reference: P. Almoro, G. Pedrini and W. Osten, Applied Optics **45**, 8596–8605
(2006), [doi:10.1364/AO.45.008596](https://doi.org/10.1364/AO.45.008596).
"""
function sbmir(intensities; propagators, maxiter=100, tol=eps(), errorfunc=msd, init=nothing)
    _intensities(intensities)
    _iterations(maxiter, tol)
    n = length(intensities)
    length(propagators) == n-1 || throw(DimensionMismatch("need one propagation pair per adjacent pair of planes"))
    foreach(_pair, propagators)
    amplitudes = [sqrt.(float.(intensity)) for intensity in intensities]
    x = _modulus(amplitudes[1], _initial_field(amplitudes[1], init))
    fields = _plane_predictions(x, amplitudes, propagators)
    for _ in 1:maxiter
        tol > 0 && all(j -> errorfunc(abs.(fields[j]), amplitudes[j]) <= tol, 1:n) && break
        for j in 1:n-1
            x = _modulus(amplitudes[j+1], _propagate(propagators[j][1], x, amplitudes[j+1]))
        end
        for j in n-1:-1:1
            x = _modulus(amplitudes[j], _propagate(propagators[j][2], x, amplitudes[j]))
        end
        fields = _plane_predictions(x, amplitudes, propagators)
    end
    fields
end

function sbmir(intensities, positions; wavelength, pixelsize, kwargs...)
    _intensities(intensities)
    positions isa AbstractVector{<:Real} || positions isa Tuple{Vararg{Real}} ||
        throw(ArgumentError("positions must be a real vector or tuple"))
    length(positions) == length(intensities) || throw(DimensionMismatch("one position is required per intensity plane"))
    all(isfinite, positions) || throw(ArgumentError("positions must be finite"))
    distances = diff(collect(float.(positions)))
    (all(>(0), distances) || all(<(0), distances)) ||
        throw(ArgumentError("positions must be strictly monotone"))
    foreach(a -> _same_size(a, intensities[1], "intensity plane"), intensities)
    intensities[1] isa AbstractMatrix{<:Real} ||
        throw(ArgumentError("the positions interface requires real matrices; use propagators for other arrays"))
    spacing = pixelsize isa Real ? (pixelsize, pixelsize) : Tuple(pixelsize)
    length(spacing) == 2 || throw(DimensionMismatch("two pixel spacings are required"))
    widths = size(intensities[1]) .* spacing
    propagators = [(x -> fresnel2(x, d, wavelength, widths...),
                    x -> fresnel2(x, -d, wavelength, widths...)) for d in distances]
    sbmir(intensities; propagators=propagators, kwargs...)
end
